async function ensureMacMediaPermissions() {
  if (process.platform !== 'darwin') {
    return;
  }

  const deniedMediaTypes = [];

  for (const mediaType of ['camera', 'microphone']) {
    try {
      let status = systemPreferences.getMediaAccessStatus(mediaType);

      if (status === 'not-determined') {
        const granted = await systemPreferences.askForMediaAccess(mediaType);
        status = granted
          ? 'granted'
          : systemPreferences.getMediaAccessStatus(mediaType);
      }

      console.log(`[media-permission] ${mediaType}:`, status);

      if (status === 'denied' || status === 'restricted') {
        deniedMediaTypes.push(mediaType);
      }
    } catch (error) {
      console.error(`[media-permission] ${mediaType} request failed:`, error);
      deniedMediaTypes.push(mediaType);
    }
  }

  console.log(
    '[media-permission] screen:',
    systemPreferences.getMediaAccessStatus('screen'),
  );

  await showMacPrivacyHelp(deniedMediaTypes);
}

function markLocalRecordingCaptureRequest() {
  localRecordingCaptureRequestExpiresAt = Date.now() + 5000;
}

function consumeLocalRecordingCaptureRequest() {
  if (Date.now() > localRecordingCaptureRequestExpiresAt) {
    localRecordingCaptureRequestExpiresAt = 0;
    return false;
  }

  localRecordingCaptureRequestExpiresAt = 0;
  return true;
}

function getMainWindowCaptureSource(sources) {
  const windowSources = sources.filter((source) =>
    source.id.startsWith('window:'),
  );
  const mainTitle = mainWindow && !mainWindow.isDestroyed()
    ? mainWindow.getTitle()
    : '';

  if (mainTitle) {
    const titleMatchedSource = windowSources.find(
      (source) => source.name === mainTitle,
    );

    if (titleMatchedSource) {
      return titleMatchedSource;
    }
  }

  return windowSources[0] || sources.find((source) =>
    source.id.startsWith('screen:'),
  );
}

function setupScreenSharePermission(targetSession = session.defaultSession) {
  targetSession.setDisplayMediaRequestHandler(
    async (request, callback) => {
      try {
        console.log('[screen-share] request:', {
          securityOrigin: request.securityOrigin,
          videoRequested: request.videoRequested,
          audioRequested: request.audioRequested,
          userGesture: request.userGesture,
          linuxDisplayBackend:
            process.platform === 'linux' ? 'auto' : undefined,
        });

        if (process.platform === 'darwin') {
          const screenStatus = systemPreferences.getMediaAccessStatus('screen');
          console.log('[screen-share] macOS permission:', screenStatus);

          if (screenStatus === 'denied' || screenStatus === 'restricted') {
            await showMacPrivacyHelp(['screen']);
            callback({});
            return;
          }
        }

        const sources = await desktopCapturer.getSources({
          types: ['screen', 'window'],
          thumbnailSize: {
            width: 360,
            height: 220,
          },
          fetchWindowIcons: true,
        });

        console.log(
          '[screen-share] sources:',
          sources.map((source) => ({
            id: source.id,
            name: source.name,
          })),
        );

        if (!sources || sources.length === 0) {
          console.error('[screen-share] no screen/window sources found');

          if (process.platform === 'darwin') {
            const screenStatus = systemPreferences.getMediaAccessStatus('screen');
            if (screenStatus !== 'granted') {
              await showMacPrivacyHelp(['screen']);
            }
          } else if (process.platform === 'linux') {
            callback({});
            await showLinuxScreenShareHelp();
            return;
          }

          callback({});
          return;
        }

        if (consumeLocalRecordingCaptureRequest()) {
          const selectedSource = getMainWindowCaptureSource(sources);

          if (!selectedSource) {
            console.error('[local-recording] no capture source found');
            callback({});
            return;
          }

          console.log('[local-recording] selected:', {
            id: selectedSource.id,
            name: selectedSource.name,
          });

          callback({
            video: selectedSource,
          });
          return;
        }

        const selectedSource = await showScreenSourcePicker(sources);

        if (!selectedSource) {
          console.log('[screen-share] user cancelled');
          setScreenAnnotationCaptureSource(null);
          callback({});
          return;
        }

        console.log('[screen-share] selected:', {
          id: selectedSource.id,
          name: selectedSource.name,
        });

        setScreenAnnotationCaptureSource(selectedSource);
        callback({
          video: selectedSource,
        });
      } catch (error) {
        console.error('[screen-share] failed:', error);
        callback({});
        await showLinuxScreenShareHelp(error);
      }
    },
    {
      useSystemPicker: false,
    },
  );
}

