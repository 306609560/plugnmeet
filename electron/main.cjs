/**
 * 处理摄像头、麦克风、屏幕捕获等权限。
 */
function isTrustedAppUrl(value) {
  if (!value) {
    return false;
  }

  try {
    const url = new URL(value);
    const isLocalPage =
      url.hostname === '127.0.0.1' ||
      url.hostname === 'localhost';
    const upstream = new URL(serverUrl);
    const isAdminApi = url.hostname === upstream.hostname;

    return isLocalPage || isAdminApi;
  } catch {
    return false;
  }
}

function setupMediaPermission(targetSession = session.defaultSession) {
  targetSession.setPermissionRequestHandler(
    (webContents, permission, callback, details) => {
      const requestingUrl = details && details.requestingUrl
        ? details.requestingUrl
        : '';
      const securityOrigin = details && 'securityOrigin' in details
        ? details.securityOrigin
        : '';

      console.log('[permission-request]', {
        permission,
        requestingUrl,
        securityOrigin,
      });

      const allowedPermissions = new Set([
        'media',
        'display-capture',
        'clipboard-sanitized-write',
        'fullscreen',
        'pointerLock',
      ]);

      if (!allowedPermissions.has(permission)) {
        callback(false);
        return;
      }

      const originCandidates = [requestingUrl, securityOrigin].filter(Boolean);

      if (originCandidates.length === 0 && webContents) {
        originCandidates.push(webContents.getURL());
      }

      callback(originCandidates.some(isTrustedAppUrl));
    },
  );

  targetSession.setPermissionCheckHandler(
    (webContents, permission, requestingOrigin, details) => {
      console.log('[permission-check]', {
        permission,
        requestingOrigin,
        requestingUrl: details.requestingUrl,
        securityOrigin: details.securityOrigin,
      });

      const allowedPermissions = new Set([
        'media',
        'display-capture',
        'clipboard-sanitized-write',
        'fullscreen',
        'pointerLock',
      ]);

      if (!allowedPermissions.has(permission)) {
        return false;
      }

      const originCandidates = [
        requestingOrigin,
        details.requestingUrl,
        details.securityOrigin,
      ].filter(Boolean);

      if (originCandidates.length === 0 && webContents) {
        originCandidates.push(webContents.getURL());
      }

      return originCandidates.some(isTrustedAppUrl);
    },
  );
}

async function createWindow() {
  const port = await startLocalServer();
  setScreenAnnotationOverlayOrigin(`http://127.0.0.1:${port}`);
  const windowIconPath = resolveAssetPath('favicon.png');

  log.info('[window] icon:', {
    path: windowIconPath,
    exists: fs.existsSync(windowIconPath),
  });

  mainWindow = new BrowserWindow({
    width: 1366,
    height: 850,
    minWidth: 1100,
    minHeight: 720,
    title: appName,
    icon: windowIconPath,

    // 去掉顶部 File Edit View Window 菜单栏
    autoHideMenuBar: true,

    webPreferences: {
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  });

  mainWindow.setMenuBarVisibility(false);
  mainWindow.removeMenu();

  if (process.platform === 'linux') {
    mainWindow.setIcon(windowIconPath);
  }

  /**
   * 关键：
   * 权限一定要绑定到当前窗口实际使用的 session 上。
   */
  setupScreenSharePermission(mainWindow.webContents.session);
  setupMediaPermission(mainWindow.webContents.session);

  mainWindow.setTitle(appName);

  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
    const targetUrl = new URL(url);
    const localAppOrigin = `http://127.0.0.1:${port}`;

    if (
      targetUrl.origin === localAppOrigin &&
      ['/api/auth/sso/start', '/im/index.html'].includes(targetUrl.pathname)
    ) {
      openInstantMessagingWindow(url, windowIconPath);
      return { action: 'deny' };
    }

    shell.openExternal(url);
    return { action: 'deny' };
  });

  /**
   * 开发环境打开 DevTools，方便查看 [screen-share] 日志。
   * 打包后不会自动打开。
   */
  if (isDev) {
    mainWindow.webContents.openDevTools({ mode: 'detach' });
  }

  mainWindow.on('closed', () => {
    stopScreenAnnotationOverlay();
    if (instantMessagingWindow && !instantMessagingWindow.isDestroyed()) {
      instantMessagingWindow.close();
    }
    mainWindow = null;
  });

  await mainWindow.loadURL(`http://127.0.0.1:${port}/`);
}

