function loadDesktopConfig() {
  const configPath = app.isPackaged
    ? path.join(process.resourcesPath, 'desktop-config.json')
    : path.join(__dirname, '..', 'build', 'desktop-config.json');
  try {
    const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
    return { serverUrl: getDesktopConfigServerUrl(config) };
  } catch (error) {
    if (isDev) {
      return {
        serverUrl: DEFAULT_SERVER_URL,
      };
    }
    throw new Error(`Invalid desktop runtime configuration: ${error.message}`, {
      cause: error,
    });
  }
}

function getUpdateFeedUrl() {
  const baseUrl = updateBaseUrl.endsWith('/')
    ? updateBaseUrl
    : `${updateBaseUrl}/`;

  return new URL(`${process.platform}/${process.arch}/`, baseUrl).toString();
}

function getMacInstallerUrl(version) {
  const fileName = `uniccmeet-${version}-macos-${process.arch}.dmg`;

  return new URL(fileName, getUpdateFeedUrl()).toString();
}

