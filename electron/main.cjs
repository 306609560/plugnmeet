function serveStatic(root, req, res) {
  let requestURL;
  let pathname;

  try {
    requestURL = new URL(req.url, 'http://127.0.0.1');
    pathname = decodeURIComponent(requestURL.pathname);
  } catch {
    res.writeHead(400);
    res.end();
    return;
  }

  const normalizedPath = path.normalize(pathname).replace(/^(\.\.[/\\])+/, '');
  let filePath = path.join(root, normalizedPath);

  if (!filePath.startsWith(root)) {
    res.writeHead(403);
    res.end();
    return;
  }

  if (pathname === '/meet' || pathname.startsWith('/meet/')) {
    const maybeFile = filePath;

    filePath =
      fs.existsSync(maybeFile) && fs.statSync(maybeFile).isFile()
        ? maybeFile
        : path.join(root, 'meet', 'index.html');
  } else if (!fs.existsSync(filePath) || !fs.statSync(filePath).isFile()) {
    filePath = path.join(root, 'index.html');
  }

  fs.readFile(filePath, (err, data) => {
    if (err) {
      console.error('[static] file read failed:', filePath, err);
      res.writeHead(404);
      res.end();
      return;
    }

    res.writeHead(200, {
      'Content-Type': contentType(filePath),
    });

    res.end(data);
  });
}

function proxyRequest(req, res) {
  let upstream;

  try {
    upstream = new URL(req.url, serverUrl);
  } catch {
    res.writeHead(400, {
      'Content-Type': 'application/json; charset=utf-8',
    });
    res.end(JSON.stringify({ error: 'invalid upstream url' }));
    return;
  }

  const transport = upstream.protocol === 'https:' ? https : http;

  const headers = {
    ...req.headers,
    host: upstream.host,
  };

  /**
   * 避免部分代理压缩响应导致 Electron 本地代理处理异常。
   */
  delete headers['accept-encoding'];

  const proxy = transport.request(
    upstream,
    {
      method: req.method,
      headers,
    },
    (proxyRes) => {
      res.writeHead(proxyRes.statusCode || 502, proxyRes.headers);
      proxyRes.pipe(res);
    },
  );

  proxy.on('error', (error) => {
    console.error('[proxy] admin api unavailable:', error);

    res.writeHead(502, {
      'Content-Type': 'application/json; charset=utf-8',
    });

    res.end(JSON.stringify({ error: 'admin api unavailable' }));
  });

  req.pipe(proxy);
}

function contentType(filePath) {
  const ext = path.extname(filePath).toLowerCase();

  const types = {
    '.html': 'text/html; charset=utf-8',
    '.js': 'text/javascript; charset=utf-8',
    '.mjs': 'text/javascript; charset=utf-8',
    '.css': 'text/css; charset=utf-8',
    '.json': 'application/json; charset=utf-8',
    '.png': 'image/png',
    '.ico': 'image/x-icon',
    '.jpg': 'image/jpeg',
    '.jpeg': 'image/jpeg',
    '.svg': 'image/svg+xml',
    '.webp': 'image/webp',
    '.gif': 'image/gif',
    '.wasm': 'application/wasm',
    '.map': 'application/json; charset=utf-8',
    '.woff': 'font/woff',
    '.woff2': 'font/woff2',
    '.ttf': 'font/ttf',
  };

  return types[ext] || 'application/octet-stream';
}

function getFreePort() {
  return new Promise((resolve, reject) => {
    const tester = net.createServer();

    tester.once('error', reject);

    tester.listen(0, '127.0.0.1', () => {
      const address = tester.address();

      tester.close(() => {
        if (!address || typeof address === 'string') {
          reject(new Error('failed to get free port'));
          return;
        }

        resolve(address.port);
      });
    });
  });
}

