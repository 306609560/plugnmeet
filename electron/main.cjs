function showUpdateDialog(options) {
  if (updateDialogOpen) {
    return Promise.resolve(null);
  }

  updateDialogOpen = true;
  const owner = mainWindow && !mainWindow.isDestroyed()
    ? mainWindow
    : undefined;
  const dialogPromise = process.platform === 'linux'
    ? showInPageDialog(options)
    : owner
      ? dialog.showMessageBox(owner, options)
      : dialog.showMessageBox(options);

  return dialogPromise
    .catch((error) => {
      log.error('[auto-update] failed to show update dialog:', error);
      return null;
    })
    .finally(() => {
      updateDialogOpen = false;
    });
}

