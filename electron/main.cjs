async function startLocalServer() {
  const distDir = getDistDir();
  const port = await getFreePort();
  const localOrigin = `http://127.0.0.1:${port}`;

  server = http.createServer((req, res) => {
    if (!req.url || !req.method) {
      res.writeHead(400);
      res.end();
      return;
    }

    if (
      req.url.startsWith('/api/') ||
      req.url.startsWith('/uploads/') ||
      req.url.startsWith('/downloads/')
    ) {
      proxyRequest(req, res);
      return;
    }

    if (
      req.method === 'POST' &&
      req.url.startsWith('/__uniccmeet/electron/local-recording-capture')
    ) {
      markLocalRecordingCaptureRequest();
      res.writeHead(204);
      res.end();
      return;
    }

    if (req.url.startsWith('/__uniccmeet/electron/screen-annotation/')) {
      const requestOrigin = req.headers.origin || (() => {
        try {
          return req.headers.referer
            ? new URL(req.headers.referer).origin
            : '';
        } catch {
          return '';
        }
      })();
      if (requestOrigin !== localOrigin) {
        res.writeHead(403);
        res.end();
        return;
      }
      void handleScreenAnnotationRequest(req, res);
      return;
    }

    serveStatic(distDir, req, res);
  });

  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, '127.0.0.1', resolve);
  });

  console.log(`[local-server] started: http://127.0.0.1:${port}/`);

  return port;
}

